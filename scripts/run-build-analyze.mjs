#!/usr/bin/env node
/**
 * Runs Vite build with ANALYZE=1 so rollup-plugin-visualizer emits dist/stats.html.
 * Also writes a committed text summary at artifacts/bundle-analysis.md.
 * Cross-platform (avoids ANALYZE=1 prefix which fails on Windows cmd).
 */
import { spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  readdirSync,
  statSync,
  writeFileSync,
  readFileSync,
} from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const env = { ...process.env, ANALYZE: '1' }

const result = spawnSync(
  process.platform === 'win32' ? 'npx.cmd' : 'npx',
  ['vite', 'build'],
  { cwd: root, env, stdio: 'inherit', shell: process.platform === 'win32' },
)

if ((result.status ?? 1) !== 0) {
  process.exit(result.status ?? 1)
}

const assetsDir = join(root, 'dist', 'assets')
const outDir = join(root, 'artifacts')
mkdirSync(outDir, { recursive: true })

const rows = []
let totalRaw = 0
let totalGzip = 0

if (existsSync(assetsDir)) {
  for (const name of readdirSync(assetsDir).sort()) {
    if (!name.endsWith('.js')) continue
    const full = join(assetsDir, name)
    const raw = statSync(full).size
    const gzip = gzipSync(readFileSync(full)).length
    totalRaw += raw
    totalGzip += gzip
    rows.push({ name, raw, gzip })
  }
}

const lines = [
  '# Bundle analysis summary',
  '',
  `Generated by \`npm run build:analyze\` on ${new Date().toISOString().slice(0, 10)}.`,
  '',
  'Interactive treemap: run `npm run build:analyze` and open `dist/stats.html` (gitignored).',
  '',
  '| Chunk | Raw | Gzip |',
  '| --- | ---: | ---: |',
  ...rows.map(
    (r) =>
      `| \`${r.name}\` | ${(r.raw / 1024).toFixed(1)} KiB | ${(r.gzip / 1024).toFixed(1)} KiB |`,
  ),
  '',
  `**Total JS:** ${(totalRaw / 1024).toFixed(1)} KiB raw / ${(totalGzip / 1024).toFixed(1)} KiB gzip (budget 200 KiB gzip).`,
  '',
]

writeFileSync(join(outDir, 'bundle-analysis.md'), lines.join('\n'), 'utf8')
console.log('Wrote artifacts/bundle-analysis.md')
process.exit(0)
